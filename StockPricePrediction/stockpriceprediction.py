# ── Rolling one-step-ahead forecast on test set ───────────────────────────────
history     = list(train)
predictions = []

for t in range(len(test)):
    model_step   = ARIMA(history, order=best_order)
    result_step  = model_step.fit()
    yhat         = result_step.forecast(steps=1)[0]
    predictions.append(yhat)
    history.append(test.iloc[t])  # Append actual observation

predictions = np.array(predictions)
actuals     = test.values


mae   = mean_absolute_error(actuals, predictions)
rmse  = np.sqrt(mean_squared_error(actuals, predictions))
mape  = np.mean(np.abs((actuals - predictions) / actuals)) * 100
r2    = r2_score(actuals, predictions)

print(f"  MAE   : {mae:.4f}")
print(f"  RMSE  : {rmse:.4f}")
print(f"  MAPE  : {mape:.2f} %")
print(f"  R²    : {r2:.4f}")

final_model  = ARIMA(series, order=best_order)
final_result = final_model.fit()

forecast_obj  = final_result.get_forecast(steps=FORECAST_DAYS)
forecast_mean = forecast_obj.predicted_mean
