series = df["Close"].dropna()

def adf_test(ts, label="Series"):
    """Augmented Dickey-Fuller test."""
    result = adfuller(ts, autolag="AIC")
    stat, p, _, _, crit, _ = result
    is_stationary = p < 0.05
    print(f"\n   ── ADF Test : {label} ──")
    print(f"   ADF Statistic : {stat:.4f}")
    print(f"   p-value       : {p:.4f}")
    for k, v in crit.items():
        print(f"   Critical ({k})  : {v:.4f}")
    print(f"   → {'✔ STATIONARY' if is_stationary else '✘ NON-STATIONARY'} (p {'<' if is_stationary else '≥'} 0.05)")
    return is_stationary


stationary = adf_test(series, label="Close Price")


diff_order = 0
series_diff = series.copy()
while not stationary and diff_order < 3:
    diff_order += 1
    series_diff = series_diff.diff().dropna()
    stationary = adf_test(series_diff, label=f"Differenced (d={diff_order})")

print(f"\n   ✔ Using d = {diff_order} for ARIMA\n")

fig, axes = plt.subplots(1, 2, figsize=(14, 4))
plot_acf(series_diff,  lags=40, ax=axes[0], title="ACF  (Differenced Series)",  color="#2196F3")
plot_pacf(series_diff, lags=40, ax=axes[1], title="PACF (Differenced Series)", color="#E91E63", method="ywm")
plt.tight_layout()
