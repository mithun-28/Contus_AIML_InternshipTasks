forecast_series = pd.Series(forecast_mean.values, index=forecast_dates)
ci_lower        = pd.Series(forecast_ci.iloc[:, 0].values, index=forecast_dates)
ci_upper        = pd.Series(forecast_ci.iloc[:, 1].values, index=forecast_dates)

