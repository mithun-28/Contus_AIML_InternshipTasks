train_series = series[:-TEST_SIZE]   # Use only training data for order selection

best_aic = np.inf
best_order = (1, diff_order, 1)      # Sensible default fallback

for p in range(0, 4):
    for q in range(0, 4):
        try:
            model_tmp = ARIMA(train_series, order=(p, diff_order, q))
            result_tmp = model_tmp.fit()
            if result_tmp.aic < best_aic:
                best_aic   = result_tmp.aic
                best_order = (p, diff_order, q)
        except Exception:
            continue

print(f"   ✔ Best ARIMA order : {best_order}  (AIC = {best_aic:.2f})\n")

train = series[:-TEST_SIZE]
test  = series[-TEST_SIZE:]
print(f"   Train size : {len(train):,} | Test size : {len(test):,}")

arima_model  = ARIMA(train, order=best_order)
arima_result = arima_model.fit()

print("\n── Model Summary (truncated) ──")
print(arima_result.summary().tables[0])   # Print just the top info table
print()

fig = arima_result.plot_diagnostics(figsize=(14, 8))
